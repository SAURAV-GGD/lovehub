import { describe, it, expect } from "vitest";
import {
  verifyYouPiWebhookSignature,
  createYouPiWebhookSignature,
} from "@/lib/youpi-client";
import { createOrderRecord, getOrderById, updateOrderStatus } from "@/lib/orders";
import { isProposalExpired } from "@/lib/proposal-storage";

describe("Part 4: YouPI-PG Gateway Integration & Security", () => {
  const testSecret = "test_webhook_secret_key_12345";

  describe("HMAC-SHA256 Signature Verification", () => {
    it("verifies authentic webhook signature generated by YouPI gateway", () => {
      const rawPayload = JSON.stringify({
        event: "SUCCESS",
        orderId: "order_test_101",
        paymentId: "yp_sess_abc123",
        amount: "31.00",
        amountPaise: 3100,
        utr: "123456789012",
      });

      const signature = createYouPiWebhookSignature(rawPayload, testSecret);
      expect(signature).toMatch(/^sha256=[a-f0-9]{64}$/);

      const isValid = verifyYouPiWebhookSignature(rawPayload, signature, testSecret);
      expect(isValid).toBe(true);
    });

    it("rejects tampered payload bytes", () => {
      const originalPayload = JSON.stringify({
        event: "SUCCESS",
        orderId: "order_test_101",
        amount: "31.00",
      });
      const signature = createYouPiWebhookSignature(originalPayload, testSecret);

      const tamperedPayload = JSON.stringify({
        event: "SUCCESS",
        orderId: "order_test_101",
        amount: "1.00", // Tampered amount!
      });

      const isValid = verifyYouPiWebhookSignature(tamperedPayload, signature, testSecret);
      expect(isValid).toBe(false);
    });

    it("rejects signature signed with wrong secret", () => {
      const rawPayload = JSON.stringify({ event: "SUCCESS", orderId: "order_1" });
      const badSignature = createYouPiWebhookSignature(rawPayload, "wrong_secret");

      const isValid = verifyYouPiWebhookSignature(rawPayload, badSignature, testSecret);
      expect(isValid).toBe(false);
    });

    it("rejects missing, null, or malformed signature headers", () => {
      const rawPayload = JSON.stringify({ event: "SUCCESS" });
      expect(verifyYouPiWebhookSignature(rawPayload, null, testSecret)).toBe(false);
      expect(verifyYouPiWebhookSignature(rawPayload, "", testSecret)).toBe(false);
      expect(verifyYouPiWebhookSignature(rawPayload, "invalid_header", testSecret)).toBe(false);
    });
  });

  describe("Order Lifecycle & State Transitions", () => {
    it("creates pending order with authoritative plan pricing", async () => {
      const orderId = `test_ord_${Date.now()}`;
      const order = await createOrderRecord({
        id: orderId,
        planId: "starter",
        amountPaise: 3100,
        currency: "INR",
        status: "pending",
        proposalId: "prop_123",
      });

      expect(order.id).toBe(orderId);
      expect(order.status).toBe("pending");
      expect(order.amountPaise).toBe(3100);

      const fetched = await getOrderById(orderId);
      expect(fetched).not.toBeNull();
      expect(fetched?.status).toBe("pending");
    });

    it("updates order to paid idempotently upon confirmation with bank UTR", async () => {
      const orderId = `test_ord_paid_${Date.now()}`;
      await createOrderRecord({
        id: orderId,
        planId: "romantic",
        amountPaise: 6900,
        status: "pending",
      });

      const updated = await updateOrderStatus(orderId, "paid", {
        utr: "987654321098",
        paymentId: "yp_paid_sess",
      });

      expect(updated?.status).toBe("paid");
      expect(updated?.utr).toBe("987654321098");

      const fetched = await getOrderById(orderId);
      expect(fetched?.status).toBe("paid");
      expect(fetched?.utr).toBe("987654321098");
    });
  });

  describe("Paid Page Activation & Preview Expiry Removal", () => {
    it("activates unpaid draft into permanent paid proposal", () => {
      // 1. Initial unpaid draft with 120s expiry
      const proposal = {
        id: "prop_unpaid_123",
        status: "draft",
        content: {
          yourName: "Rohan",
          partnerName: "Pooja",
          isPaid: false,
          expiresAt: Date.now() + 120_000,
        },
      };

      expect(isProposalExpired(proposal.content)).toBe(false);

      // 2. Simulate payment confirmation action
      proposal.status = "final";
      proposal.content.isPaid = true;
      delete (proposal.content as Record<string, unknown>).expiresAt;

      // 3. Verification: Proposal is now permanently active
      expect(proposal.status).toBe("final");
      expect(proposal.content.isPaid).toBe(true);
      expect(proposal.content.expiresAt).toBeUndefined();
      expect(isProposalExpired(proposal.content)).toBe(false);
    });

    it("ensures duplicate webhooks are recognized and skipped idempotently", () => {
      const processedEventIds = new Set<string>();

      function processWebhookIdempotently(eventId: string): { processed: boolean; idempotent: boolean } {
        if (processedEventIds.has(eventId)) {
          return { processed: false, idempotent: true };
        }
        processedEventIds.add(eventId);
        return { processed: true, idempotent: false };
      }

      const eventId = "yp_event_payment_123456";

      // First webhook delivery
      const first = processWebhookIdempotently(eventId);
      expect(first.processed).toBe(true);
      expect(first.idempotent).toBe(false);

      // Duplicate delivery (gateway retry or network replay)
      const second = processWebhookIdempotently(eventId);
      expect(second.processed).toBe(false);
      expect(second.idempotent).toBe(true);
    });
  });
});
